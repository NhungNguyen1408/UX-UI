-- BeautyGlow - MySQL 8.0+ (utf8mb4) - demo học tập
CREATE DATABASE IF NOT EXISTS beautyglow_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE beautyglow_db;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 phone VARCHAR(20),
 role ENUM('CUSTOMER','ADMIN') NOT NULL DEFAULT 'CUSTOMER',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS addresses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 recipient_name VARCHAR(120) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 street_address VARCHAR(255) NOT NULL,
 ward VARCHAR(100), city VARCHAR(100) NOT NULL,
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT fk_address_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_addresses_user (user_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS brands (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(150) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(150) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 category_id BIGINT UNSIGNED NOT NULL,
 brand_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(255) NOT NULL,
 slug VARCHAR(255) NOT NULL UNIQUE,
 description TEXT,
 price_vnd INT UNSIGNED NOT NULL,
 original_price_vnd INT UNSIGNED,
 stock INT UNSIGNED NOT NULL DEFAULT 0,
 image_url VARCHAR(255),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_product_category FOREIGN KEY(category_id) REFERENCES categories(id),
 CONSTRAINT fk_product_brand FOREIGN KEY(brand_id) REFERENCES brands(id),
 INDEX idx_product_category(category_id), INDEX idx_product_brand(brand_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cart_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL DEFAULT 1,
 UNIQUE KEY uq_cart_user_product(user_id, product_id),
 CONSTRAINT fk_cart_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_cart_product FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS favorites (
 user_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id, product_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 discount_vnd INT UNSIGNED NOT NULL,
 minimum_order_vnd INT UNSIGNED NOT NULL DEFAULT 0,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 expires_at DATETIME NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_code VARCHAR(32) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 recipient_name VARCHAR(120) NOT NULL,
 recipient_phone VARCHAR(20) NOT NULL,
 shipping_address VARCHAR(500) NOT NULL,
 subtotal_vnd INT UNSIGNED NOT NULL,
 discount_vnd INT UNSIGNED NOT NULL DEFAULT 0,
 shipping_vnd INT UNSIGNED NOT NULL DEFAULT 20000,
 total_vnd INT UNSIGNED NOT NULL,
 status ENUM('PENDING','CONFIRMED','SHIPPING','DELIVERED','CANCELLED') NOT NULL DEFAULT 'PENDING',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_order_user FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_order_user_date(user_id, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 product_name VARCHAR(255) NOT NULL,
 unit_price_vnd INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL UNIQUE,
 method ENUM('COD','MOMO_SIMULATION') NOT NULL,
 status ENUM('PENDING','COLLECT_ON_DELIVERY','PAID','FAILED') NOT NULL DEFAULT 'PENDING',
 amount_vnd INT UNSIGNED NOT NULL,
 paid_at TIMESTAMP NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 rating TINYINT UNSIGNED NOT NULL,
 comment TEXT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
 INDEX idx_review_product(product_id)
) ENGINE=InnoDB;
